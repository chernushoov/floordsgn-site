#!/usr/bin/env node
/*
 * build-partials.js — single source of truth for the site header & footer.
 *
 * This is a vanilla static site (no SSI / no build-time includes — Parcel only
 * minifies). Header/footer markup was therefore copy-pasted into every page and
 * drifted, especially the logo. This script is the propagation step:
 *
 *   1. Edit partials/header.html and/or partials/footer.html (the ONE source).
 *   2. Run `node scripts/build-partials.js`.
 *   3. The canonical markup is written into every tracked site page, between
 *      generated BEGIN/END markers. Idempotent — re-run any time to re-sync.
 *
 * Partials use ROOT-ABSOLUTE paths (/images/..., /floors/...), so the identical
 * snippet is valid at any directory depth (root, /floors/, /floors/<cat>/, ...).
 *
 * Scope: tracked HTML only (`git ls-files '*.html'`). Skips partials/, dist/,
 * astro/, node_modules/, landing.html (FROZEN), and any page that has neither
 * our <header class="header"> nor our <footer class="footer"> (e.g. configurator,
 * language-switcher, admin). Foreign scraped headers/footers (Shopify/WP/AEM in
 * untracked data/ research/) are excluded both by git-tracking and by the exact
 * class="header" / class="footer" match.
 *
 * Usage:
 *   node scripts/build-partials.js            # propagate to all tracked pages
 *   node scripts/build-partials.js --dry      # report what would change, write nothing
 *   node scripts/build-partials.js a.html b/c.html   # limit to specific files
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const DRY = args.includes('--dry');
const only = args.filter((a) => a !== '--dry');

const HEADER = fs.readFileSync(path.join(ROOT, 'partials/header.html'), 'utf8').trim();
const FOOTER = fs.readFileSync(path.join(ROOT, 'partials/footer.html'), 'utf8').trim();

const H_BEGIN = '<!-- partials:header:start (generated by scripts/build-partials.js — edit partials/header.html, not here) -->';
const H_END = '<!-- partials:header:end -->';
const F_BEGIN = '<!-- partials:footer:start (generated by scripts/build-partials.js — edit partials/footer.html, not here) -->';
const F_END = '<!-- partials:footer:end -->';

const headerBlock = `${H_BEGIN}\n${HEADER}\n${H_END}`;
const footerBlock = `${F_BEGIN}\n${FOOTER}\n${F_END}`;

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// first occurrence of our header/footer; the exact class="header"/class="footer"
// token excludes foreign tags (<header-menu>, class="banner", cmp-header, ...).
const headerRe = /<header\b[^>]*class="header"[^>]*>[\s\S]*?<\/header>/i;
const footerRe = /<footer\b[^>]*class="footer"[^>]*>[\s\S]*?<\/footer>/i;
const headerMarkerRe = new RegExp(`${esc(H_BEGIN)}[\\s\\S]*?${esc(H_END)}`);
const footerMarkerRe = new RegExp(`${esc(F_BEGIN)}[\\s\\S]*?${esc(F_END)}`);

const SKIP_DIR = /^(partials|dist|astro|node_modules)\//;
const SKIP_FILE = new Set(['landing.html']);

let files = execSync("git ls-files '*.html'", { cwd: ROOT }).toString().trim().split('\n').filter(Boolean);
if (only.length) files = only;
files = files.filter((f) => !SKIP_DIR.test(f) && !SKIP_FILE.has(path.basename(f)));

let hChanged = 0;
let fChanged = 0;
let touched = 0;
const noBlock = [];

for (const rel of files) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) continue;
  let src = fs.readFileSync(abs, 'utf8');
  const orig = src;
  let hadHeader = false;
  let hadFooter = false;

  if (headerMarkerRe.test(src)) { src = src.replace(headerMarkerRe, headerBlock); hadHeader = true; }
  else if (headerRe.test(src)) { src = src.replace(headerRe, headerBlock); hadHeader = true; }

  if (footerMarkerRe.test(src)) { src = src.replace(footerMarkerRe, footerBlock); hadFooter = true; }
  else if (footerRe.test(src)) { src = src.replace(footerRe, footerBlock); hadFooter = true; }

  if (!hadHeader && !hadFooter) { noBlock.push(rel); continue; }
  if (src !== orig) {
    if (hadHeader) hChanged++;
    if (hadFooter) fChanged++;
    touched++;
    if (!DRY) fs.writeFileSync(abs, src);
  }
}

const verb = DRY ? 'would update' : 'updated';
console.log(`build-partials: ${verb} ${touched} page(s) — header in ${hChanged}, footer in ${fChanged}.`);
console.log(`skipped (no header/footer block): ${noBlock.length}${noBlock.length ? ' -> ' + noBlock.join(', ') : ''}`);
if (DRY) console.log('(--dry: no files written)');
